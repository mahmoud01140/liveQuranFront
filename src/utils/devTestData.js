/**
 * تعبئة الاستبيان ببيانات اختبارية
 * @param {Function} setSurveyAnswer — دالة من examStore
 * @param {string} regType — نوع التسجيل (student/teacher/senior)
 * @returns {number[]} الإجابات المملوءة
 */
export function fillSurveyTestData(setSurveyAnswer, regType = 'student') {
  const answers = TEST_SURVEY_ANSWERS[regType] || TEST_SURVEY_ANSWERS.student;
  answers.forEach((answer, index) => {
    setSurveyAnswer(index, answer);
  });
  return answers;
}

/**
 * تعبئة امتحان تحديد المستوى ببيانات اختبارية
 * @param {Function} setAnswer — دالة من examStore
 * @param {string} regType — نوع التسجيل
 * @param {'correct'|'partial'} mode — نمط الإجابة (صحيح بالكامل أو جزئي)
 * @returns {Object} الإجابات المملوءة
 */
export function fillExamTestData(setAnswer, regType = 'student', mode = 'correct') {
  const source = mode === 'partial' ? TEST_EXAM_ANSWERS_PARTIAL : TEST_EXAM_ANSWERS;
  const answers = source[regType] || source.student;
  Object.entries(answers).forEach(([qIdx, aIdx]) => {
    setAnswer(Number(qIdx), aIdx);
  });
  return answers;
}
